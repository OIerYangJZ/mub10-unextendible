#!/usr/bin/env python
"""Ray catalogue for the Fourier pair (I, F10) from the public PHCpack cyclic-10 solution list (numerical; a pilot).
Cyclic-10: C_k(x) = sum_j prod_{r<k} x_{j+r} = 0 (k = 1..9), prod x = 1.  A unimodular root x gives the biunimodular
sequence z with z_0 = 1, z_{j+1} = x_j z_j (Bjorck); psi = z / sqrt10 is unbiased to I and F10, and every such ray
(up to phase) arises this way.  Steps: parse the 1747 representatives, expand by the 20-element group generated by the
cyclic shift and the reversal (as stated on the page), Newton-refine all roots (batched), keep the unimodular ones,
build the rays, deduplicate up to phase, verify unbiasedness, identify the 40 product rays (Gaussian chirps), and save.
Usage: python cyclic10_catalogue.py <phc_html_file> <out.npz> [roots.bin]
"""
import sys, re, time
import numpy as np

T0 = time.time()
def log(*a): print("[%6.1fs]" % (time.time() - T0), *a, flush=True)

def parse(fn):
    txt = open(fn, encoding="latin-1").read()
    sols = []
    for blk in re.split(r"solution\s+\d+\s*:", txt)[1:]:
        vals = re.findall(r"z(\d)\s*:\s*([-+0-9.E]+)\s+([-+0-9.E]+)", blk)
        if len(vals) < 10: continue
        v = np.zeros(10, complex)
        for i, re_, im_ in vals[:10]:
            v[int(i)] = float(re_) + 1j * float(im_)
        sols.append(v)
    return np.array(sols)

def cyclic_F(X):
    """X: (n,10) -> residuals (n,10): C_1..C_9 and prod - 1"""
    n = X.shape[0]; R = np.zeros((n, 10), complex)
    for k in range(1, 10):
        acc = np.zeros(n, complex)
        for j in range(10):
            p = np.ones(n, complex)
            for r in range(k): p = p * X[:, (j + r) % 10]
            acc += p
        R[:, k - 1] = acc
    R[:, 9] = np.prod(X, axis=1) - 1
    return R

def jac(X, h=1e-7):
    n = X.shape[0]; J = np.zeros((n, 10, 10), complex); F0 = cyclic_F(X)
    for i in range(10):         # the system is polynomial (holomorphic): complex-step derivative along a real step
        Xp = X.copy(); Xp[:, i] += h
        J[:, :, i] = (cyclic_F(Xp) - F0) / h
    return J, F0

def newton(X, it=6):
    for _ in range(it):
        J, F = jac(X)
        dx = np.linalg.solve(J, F[..., None])[..., 0]
        X = X - dx
    return X, np.abs(cyclic_F(X)).max(axis=1)

def main():
    src, out = sys.argv[1], sys.argv[2]
    reps = parse(src); log("parsed %d representatives" % len(reps))
    # expand by <shift, reversal>: shift x -> x_{j+1}, reversal x -> x_{9-j}
    allx = []
    for x in reps:
        for rev in (False, True):
            y = x[::-1] if rev else x
            for s in range(10):
                allx.append(np.roll(y, -s))
    X = np.array(allx); log("expanded to %d roots" % len(X))
    X, res = newton(X); log("Newton: max residual %.2e, median %.2e" % (res.max(), np.median(res)))
    # dedupe roots
    key = np.round(X, 7); _, idx = np.unique(key.view(np.float64).reshape(len(X), -1), axis=0, return_index=True)
    X = X[np.sort(idx)]; log("distinct roots: %d (expected 34940)" % len(X))
    uni = np.abs(np.abs(X) - 1).max(axis=1) < 1e-8
    Xu = X[uni]; log("unimodular roots: %d" % len(Xu))
    # rays: z_0 = 1, z_{j+1} = x_j z_j
    Z = np.ones((len(Xu), 10), complex)
    for j in range(9): Z[:, j + 1] = Xu[:, j] * Z[:, j]
    assert np.abs(Xu[:, 9] * Z[:, 9] - 1).max() < 1e-8         # periodicity (prod x = 1)
    psi = Z / np.sqrt(10)
    # dedupe up to phase (z_0 = 1 already fixes the phase)
    k2 = np.round(psi, 7); _, idx = np.unique(k2.view(np.float64).reshape(len(psi), -1), axis=0, return_index=True)
    psi = psi[np.sort(idx)]; log("distinct rays (dephased): %d" % len(psi))
    F = np.exp(2j * np.pi * np.outer(np.arange(10), np.arange(10)) / 10) / np.sqrt(10)
    eI = np.abs(np.abs(psi) ** 2 - 0.1).max(); eF = np.abs(np.abs(psi @ F.conj()) ** 2 - 0.1).max()
    log("unbiasedness: to I %.1e, to F10 %.1e" % (eI, eF))
    # product rays: Gaussian chirps z_n = exp(pi i (c n^2 + 2 d n)/10), c in {1,3,7,9}
    n = np.arange(10); chirps = []
    for c in (1, 3, 7, 9):
        for d in range(10):
            chirps.append(np.exp(1j * np.pi * (c * n * n + 2 * d * n) / 10) / np.sqrt(10))
    chirps = np.array(chirps)
    ov = np.abs(chirps.conj() @ psi.T) ** 2
    prod_idx = sorted(set(np.argmax(ov, axis=1).tolist()))
    found = int((ov.max(axis=1) > 1 - 1e-9).sum())
    log("Gaussian chirps found in the catalogue: %d / 40 (distinct %d)" % (found, len(prod_idx)))
    np.savez(out, psi=psi, product=np.array(prod_idx), roots=X)
    if len(sys.argv) > 3:                                   # all 34,940 roots for c10krawczyk (int32 n, n x 10 complex128)
        with open(sys.argv[3], "wb") as fb:
            fb.write(np.int32(len(X)).tobytes()); fb.write(np.ascontiguousarray(X, dtype="<c16").tobytes())
        log("wrote %s" % sys.argv[3])
    log("saved %s" % out)

if __name__ == "__main__":
    main()
